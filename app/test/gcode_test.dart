import 'dart:convert';
import 'dart:typed_data';

import 'package:datum/io/gcode_loader.dart';
import 'package:datum/model/print_summary.dart';
import 'package:flutter_test/flutter_test.dart';

GcodeData parse(String s) =>
    parseGcode(Uint8List.fromList(utf8.encode(s)), 't.nc');

void main() {
  test('parámetros, expresiones y bucles WHILE/DO (Fanuc)', () {
    final d = parse(
      'G21 G90\n#1=0\nWHILE [#1 LT 3] DO1\nG1 X[#1*20+5] F100\n#1=#1+1\nEND1\n',
    );
    expect(d.stats.cnc!.cutMm, closeTo(5 + 20 + 20, 1e-6));
  });

  test('subrutinas LinuxCNC con parámetros', () {
    final d = parse(
      'G21 G90\nO10 sub\nG1 X[#1] F100\nO10 endsub\nO10 call [7]\nO10 call [9]\n',
    );
    expect(d.stats.cnc!.cutMm, closeTo(7 + 2, 1e-6));
  });

  test('ciclo G81 repetido en X y G54 antes del movimiento', () {
    final d = parse(
      'G90 G54 G0 X0 Y0 Z5\nG81 X0 Y0 Z-5 R2 F100\nX10\nX20\nG80\n',
    );
    expect(d.stats.cnc!.wcsCount, 1);
    // 3 taladros: R2→Z-5 en avance = 7 mm cada uno
    expect(d.stats.cnc!.cutMm, closeTo(21, 1e-6));
  });

  test('G10 L2 desplaza cada sistema de trabajo y G92 no salta', () {
    final d = parse(
      'G21 G90\nG10 L2 P1 X100\nG10 L2 P2 Y50\nG54\nG0 Z5\nG1 X10 Z-1 F100\n'
      'G55\nG0 Z5\nG0 X0 Y0\nG1 Z-1\nG1 X10\nG92 X0\nG1 X5\n',
    );
    final t = d.build();
    // G54: x 100..110; G55: x 0..10, y 50; G92 X0 en x=10 → siguiente corte hasta x=15
    expect(t.bounds.min[0], closeTo(0, 1e-6));
    expect(t.bounds.max[0], closeTo(110, 1e-6));
    expect(t.bounds.max[1], closeTo(50, 1e-6));
    expect(d.stats.cnc!.wcsCount, 2);
  });

  test('M98 con repeticiones y M99', () {
    final d = parse(
      'O1\nG21 G90\nM98 P2 L2\nM30\nO2\nG1 X10 F100\nG1 X0\nM99\n',
    );
    expect(d.stats.cnc!.cutMm, closeTo(40, 1e-6));
  });

  test('G91.1 no cambia a incremental y avisa de bajada en rápido', () {
    final d = parse('G90 G91.1\nG0 X10 Z-3\nG1 X20 F100\n');
    expect(d.stats.cnc!.rapidPlunges, 1);
    expect(d.max[0], 20);
  });

  test('bucle infinito se corta', () {
    final d = parse('O1 while [1]\nG1 X1 F10\nG1 X0\nO1 endwhile\n');
    expect(d.stats.cnc!.usesFlow, isTrue);
  });

  test('FDM: tiempo y filamento declarados por el laminador', () {
    final d = parse(
      '; generated by PrusaSlicer 2.8.1\n; filament used [mm] = 100.0\n; filament used [g] = 0.3\n; estimated printing time (normal mode) = 1h 2m 3s\n'
      ';LAYER_CHANGE\n;Z:0.2\nG1 Z0.2 F1000\nG1 X10 E1 F1200\n;LAYER_CHANGE\n;Z:0.4\nG1 Z0.4\nG1 X0 E2\nM600\n',
    );
    final t = d.build();
    expect(t.layerCount, 2);
    expect(t.layerZ[0], closeTo(0.2, 1e-6));
    expect(t.summary.seconds, 3723);
    expect(t.summary.totalGrams, closeTo(0.3, 1e-9));
    expect(t.stats.colorChangeLayers, [1]);
  });

  test('duraciones', () {
    expect(parseDuration('7 hours 17 minutes'), 7 * 3600 + 17 * 60);
    expect(parseDuration('1d 2h 3m 4s'), 86400 + 7200 + 180 + 4);
  });
}
