#!/usr/bin/env python3
"""Genera .bgcode sintéticos (sin compresión, deflate y heatshrink+MeatPack) para probar el lector.
OJO: son archivos hechos por mí siguiendo la especificación de Prusa; no son archivos reales de PrusaSlicer."""
import os, struct, zlib, math

OUT = os.path.join(os.path.dirname(__file__), '..', 'testdata', 'formatos')

def make_gcode():
    L = ['; generated by Datum test\n', 'M83\n', 'G90\n']
    e_total = 0
    for layer in range(30):
        z = 0.2 + 0.2 * layer
        L.append(';LAYER_CHANGE\n;Z:%.1f\n' % z)
        L.append('G1 Z%.1f F1200\n' % z)
        for feat, off in (('External perimeter', 0.0), ('Perimeter', 0.45), ('Internal infill', 1.2)):
            L.append(';TYPE:%s\n' % feat)
            s = 10 + off
            pts = [(s, s), (30 - off, s), (30 - off, 30 - off), (s, 30 - off), (s, s)]
            L.append('G1 X%.3f Y%.3f F6000\n' % pts[0])
            for p in pts[1:]:
                L.append('G1 X%.3f Y%.3f E0.8 F1800\n' % p)
        L.append('G1 X5 Y5 F9000\n')
    return ''.join(L).encode()

def heatshrink_encode(data, wbits=12, lbits=4):
    out = bytearray(); cur = 0; nb = 0
    def put(v, n):
        nonlocal cur, nb
        for i in range(n - 1, -1, -1):
            cur = (cur << 1) | ((v >> i) & 1); nb += 1
            if nb == 8:
                out.append(cur); cur = 0; nb = 0
    win = 1 << wbits; maxlen = 1 << lbits
    i = 0
    while i < len(data):
        best_len, best_off = 0, 0
        for off in range(1, min(win, i) + 1):
            l = 0
            while l < maxlen and i + l < len(data) and data[i + l - off] == data[i + l] if i + l - off >= 0 else False:
                l += 1
            if l > best_len:
                best_len, best_off = l, off
                if l == maxlen: break
        if best_len >= 3:
            put(0, 1); put(best_off - 1, wbits); put(best_len - 1, lbits); i += best_len
        else:
            put(1, 1); put(data[i], 8); i += 1
    if nb: out.append(cur << (8 - nb) & 0xFF)
    return bytes(out)

NIB = {c: i for i, c in enumerate('0123456789')}
NIB.update({'.': 0xA, ' ': 0xB, '\n': 0xC, 'G': 0xD, 'X': 0xE})

def meatpack_encode(data):
    out = bytearray(b'\xff\xff\xfb'); packing = True
    for line in data.decode().split('\n')[:-1]:
        if line.startswith(';'):
            if packing: out += b'\xff\xff\xfa'; packing = False
            out += line.encode() + b'\n'
            continue
        if not packing: out += b'\xff\xff\xfb'; packing = True
        s = line.split(';')[0].replace(' ', '').upper() + '\n'
        i = 0
        while i < len(s):
            c1 = s[i]; c2 = s[i + 1] if i + 1 < len(s) else '\n'
            i += 2
            n1 = NIB.get(c1, 0xF); n2 = NIB.get(c2, 0xF)
            out.append((n2 << 4) | n1)
            if n1 == 0xF: out.append(ord(c1))
            if n2 == 0xF: out.append(ord(c2))
    return bytes(out)

def block(btype, comp, raw, params, data=None):
    payload = raw if data is None else data
    h = struct.pack('<HHI', btype, comp, len(raw))
    if comp != 0: h += struct.pack('<I', len(payload))
    return h + params + payload

def build(name, gcode_comp, gcode_enc):
    g = make_gcode()
    enc = meatpack_encode(g) if gcode_enc else g
    if gcode_comp == 0: data = enc
    elif gcode_comp == 1: data = zlib.compress(enc)
    elif gcode_comp == 3: data = heatshrink_encode(enc, 12, 4)
    elif gcode_comp == 2: data = heatshrink_encode(enc, 11, 4)
    f = b'GCDE' + struct.pack('<IH', 1, 0)
    f += block(3, 0, b'printer_model=MK4S\nnozzle_diameter=0.4\n', struct.pack('<H', 0))
    f += block(4, 0, b'estimated printing time (normal mode)=14m 20s\nfilament used [mm]=1200.5\n', struct.pack('<H', 0))
    f += block(2, 0, b'layer_height=0.2\nperimeters=2\n', struct.pack('<H', 0))
    f += block(1, gcode_comp, enc, struct.pack('<H', 1 if gcode_enc else 0), data)
    open(os.path.join(OUT, name), 'wb').write(f)
    print(name, len(f), 'bytes')

build('prueba_sin_comprimir.bgcode', 0, False)
build('prueba_deflate.bgcode', 1, False)
build('prueba_heatshrink_meatpack.bgcode', 3, True)
